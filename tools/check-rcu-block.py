#!/usr/bin/env python3
"""The RCU's RTL block in lock-step with its C++ model (TI rev 394; RI-24 (3)).

    check-rcu-block.py build DIR                 the harness, once: DIR/tb
    check-rcu-block.py vectors DUMP.vcd OUT [--corrupt CYCLE:PORT]
    check-rcu-block.py run DIR STIM KERNEL [--keep]

ccv-skel --port-dump rcu=FILE (RA-34; sim/skel/portdump.cpp) writes the RCU
block's ports a sample a cycle, inputs and the model's outputs, named as
rtl/top/ports/ccv_rcu_ports.svh names them and as the block itself sees them
(inside its hardening wrapper: a flopped sending end shows the block's own
register, portdump.h). So the DUT is ccv_rcu, RI's assembled block
(rtl/rcu/ccv_rcu.sv), not the wrapper ccv_rcu_w, whose boundary flops the
dump has already accounted for.

The harness drives every input each cycle from the dump (rst_n included, so
the block sees the skeleton's own reset sequence and flops it itself, RST-1)
and compares every output each cycle with the model's value. It stops at the
first mismatch and prints its cycle, port, expected and got.

What is not compared for equality, each for a reason, and each reported:
  - every output `_wake`: the dump's are DERIVED (portdump.h: no block of
    the skeleton drives a wake, Q-33; the dump writes the latest legal one).
    Whether a wake was owed depends on the receiver's gate, which a block
    harness has not (rtl/if/ccv_common_chk_wake.sv: the obligation starts
    when the receiver gates; the SV top's checker bank judges it). So the
    harness only NOTES, never fails on, a valid the block sends at T with
    no wake of its channel in (T' - LAT, T - LAT], T' the channel's
    previous valid, LAT = CCV_WAKE_LAT: the sender's rule in its strict,
    receiver-blind form, for RI to read beside a divergence;
  - csr_rsp and csr_credit: the skeleton models no CSR traffic (portdump.h),
    so csr_req is tied idle and both must stay 0;
  - the CCV_TRACE (`_tid`) and CCV_CHECK (`clk_gated`) ports: not built.
The input wakes are the dump's derived ones: the latest legal wake for every
message, which a correctly gating block must meet.

A stimulus file is one record a line, `TAG K HEX`: `C t 0` opens cycle t,
`I k v` sets input k, `O k v` sets output k's expected value, `E t 0` ends
the cycle (settle, compare, clock). Only changes are written.
"""
import importlib.util
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSR_IDLE = ("csr_rsp", "csr_credit")   # no CSR traffic in the skeleton: held at 0


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, os.path.join(ROOT, "tools", path))
    m = importlib.util.module_from_spec(spec)
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    spec.loader.exec_module(m)
    return m


def ports():
    """[(dir, width, name)] of ccv_rcu outside any `ifdef`, core_clk aside,
    in the generated port list's order (tools/gen-top.py's block_ports)."""
    cpd = _load("check_port_dump", "check-port-dump.py")
    gt = cpd.gen_top()
    cwd = os.getcwd()
    os.chdir(ROOT)
    try:
        d, blocks, binst, chans, cinst, ninst, common = gt.load()
    finally:
        os.chdir(cwd)
    P = gt.block_ports("rcu", chans, ninst, common, len(binst))
    return [(dr, w, n) for dr, w, n, guard, *_ in P if not guard and n != "core_clk"]


def wake_lat():
    t = open(os.path.join(ROOT, "rtl", "generated", "ccv_params_pkg.sv")).read()
    m = re.search(r"\bCCV_WAKE_LAT\s*=\s*(\d+)", t)
    if not m:
        raise SystemExit("check-rcu-block: no CCV_WAKE_LAT in ccv_params_pkg")
    return int(m.group(1))


def build(d):
    P = ports()
    ins = [p for p in P if p[0] == "input"]
    outs = [p for p in P if p[0] == "output"]
    maxw = max(w for _, w, _ in P)
    lat = wake_lat()
    L = []
    a = L.append
    a("// Generated by tools/check-rcu-block.py: ccv_rcu driven from a ccv-skel")
    a("// port dump, every output compared each cycle with the model's.")
    a("module rcublk_tb;")
    a("  logic core_clk = 1'b0;")
    for _, w, n in ins:
        a("  logic [%d:0] i_%s = '0;" % (w - 1, n))
    for _, w, n in outs:
        a("  wire  [%d:0] o_%s;" % (w - 1, n))
        a("  logic [%d:0] e_%s = '0;" % (w - 1, n))
    conns = [".core_clk(core_clk)"] + [".%s(i_%s)" % (n, n) for _, _, n in ins] + \
            [".%s(o_%s)" % (n, n) for _, _, n in outs]
    a("  ccv_rcu dut (\n    " + ",\n    ".join(conns) + ");")
    # The wake rule's bookkeeping, per output wake: its history, and the
    # channel's previous valid.
    wakes = []
    for _, w, n in outs:
        if n.endswith("_wake"):
            base = n[:-len("_wake")]
            vs = [m for _, _, m in outs
                  if m.endswith("_valid") and re.fullmatch(re.escape(base) + r"(_s\d+)?_valid", m)]
            if not vs:
                raise SystemExit("check-rcu-block: output %s has no valid" % n)
            wakes.append((n, vs))
            a("  bit wh_%s [];" % n)
            a("  int pv_%s = -1000000;" % n)
    a("  int fd, t, k, n = 0, bad = 0, keep = 0, wbad = 0, maxp = 40;")
    a("  string stim, tag;")
    a("  logic [%d:0] v;" % (maxw - 1))
    # Every mismatch of a cycle is printed; without +keep=1 the run stops
    # after the first cycle that has one.
    a("  task automatic miss(input string port, input logic [%d:0] e, input logic [%d:0] g);"
      % (maxw - 1, maxw - 1))
    a("    bad++;")
    a("    if (bad <= maxp) $display(\"RCUBLK MISMATCH cycle %0d port %s expected %0h got %0h\", t, port, e, g);")
    a("  endtask")
    a("  task automatic set_in(input int k, input logic [%d:0] v);" % (maxw - 1))
    a("    case (k)")
    for i, (_, w, n) in enumerate(ins):
        a("      %d: i_%s = v[%d:0];" % (i, n, w - 1))
    a("      default: begin $display(\"RCUBLK bad input index %0d\", k); $fatal; end")
    a("    endcase")
    a("  endtask")
    a("  task automatic set_out(input int k, input logic [%d:0] v);" % (maxw - 1))
    a("    case (k)")
    for i, (_, w, n) in enumerate(outs):
        a("      %d: e_%s = v[%d:0];" % (i, n, w - 1))
    a("      default: begin $display(\"RCUBLK bad output index %0d\", k); $fatal; end")
    a("    endcase")
    a("  endtask")
    a("  task automatic check();")
    nchk = 0
    for _, w, n in outs:
        if n.endswith("_wake"):
            continue
        nchk += 1
        a("    if (o_%s !== e_%s) miss(\"%s\", %d'(e_%s), %d'(o_%s));"
          % (n, n, n, maxw, n, maxw, n))
    a("  endtask")
    a("  task automatic wake_rule();")
    for n, vs in wakes:
        a("    if (t < wh_%s.size()) wh_%s[t] = o_%s;" % (n, n, n))
        a("    if (%s) begin" % " | ".join("o_%s" % x for x in vs))
        a("      automatic bit ok = 1'b0;")
        a("      for (int c = (pv_%s - %d + 1 < 0 ? 0 : pv_%s - %d + 1); c <= t - %d; c++)"
          % (n, lat, n, lat, lat))
        a("        if (wh_%s[c]) ok = 1'b1;" % n)
        a("      if (!ok) begin")
        a("        wbad++;")
        a("        if (wbad <= 10) $display(\"RCUBLK WAKE-NOTE cycle %%0d port %s: a valid with no wake "
          "in (%%0d, %%0d]\", t, pv_%s - %d, t - %d);" % (n, n, lat, lat))
        a("      end")
        a("      pv_%s = t;" % n)
        a("    end")
    a("  endtask")
    a("  initial begin")
    a("    void'($value$plusargs(\"stim=%s\", stim));")
    a("    void'($value$plusargs(\"keep=%d\", keep));")
    a("    void'($value$plusargs(\"n=%d\", n));")
    a("    void'($value$plusargs(\"maxp=%d\", maxp));")
    for n, _ in wakes:
        a("    wh_%s = new[n + 1];" % n)
    a("    fd = $fopen(stim, \"r\");")
    a("    if (fd == 0) begin $display(\"RCUBLK no stimulus %s\", stim); $fatal; end")
    a("    while ($fscanf(fd, \"%s %d %h\", tag, k, v) == 3) begin")
    a("      if (tag == \"C\") t = k;")
    a("      else if (tag == \"I\") set_in(k, v);")
    a("      else if (tag == \"O\") set_out(k, v);")
    a("      else if (tag == \"E\") begin")
    a("        #1;")
    a("        check();")
    a("        wake_rule();")
    a("        if (bad && !keep) begin")
    a("          $display(\"RCUBLK FAIL at cycle %0d\", t);")
    a("          break;")
    a("        end")
    a("        core_clk = 1'b1; #1; core_clk = 1'b0; #1;")
    a("      end")
    a("    end")
    a("    $fclose(fd);")
    a("    $display(\"RCUBLK DONE cycles %%0d outputs %d wakes %d mismatches %%0d wake_misses %%0d\", "
      "t + 1, bad, wbad);" % (nchk, len(wakes)))
    a("    $finish;")
    a("  end")
    a("endmodule")
    os.makedirs(d, exist_ok=True)
    tb = os.path.join(d, "rcublk_tb.sv")
    open(tb, "w").write("\n".join(L) + "\n")
    rtl = sorted(os.path.join(ROOT, "rtl", "rcu", f) for f in os.listdir(os.path.join(ROOT, "rtl", "rcu"))
                 if f.endswith(".sv") and f != "rcu_dec_pkg.sv")
    cmd = ["verilator", "--binary", "--timing", "-j", "0", "-O2", "--assert",
           "-Wno-fatal", "-Wno-lint", "-Wno-style",
           "--top-module", "rcublk_tb", "--Mdir", d, "-o", "tb",
           "-I" + os.path.join(ROOT, "rtl", "include"), "-I" + os.path.join(ROOT, "rtl", "generated"),
           "-I" + os.path.join(ROOT, "rtl", "top", "ports"),
           os.path.join(ROOT, "rtl", "generated", "ccv_params_pkg.sv"),
           os.path.join(ROOT, "rtl", "ccv_assert_pkg.sv"),
           os.path.join(ROOT, "rtl", "rcu", "rcu_dec_pkg.sv"),
           os.path.join(ROOT, "rtl", "ctech", "sim", "ccv_common_ctech_icg.sv"),
           os.path.join(ROOT, "rtl", "clk", "ccv_common_clk.sv")] + rtl + [tb]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write((r.stdout + r.stderr)[-3000:])
        raise SystemExit("check-rcu-block: harness build failed")
    excl = [n for _, _, n in outs if n.endswith("_wake")]
    print("harness: %d inputs, %d outputs compared each cycle (%s held to 0), "
          "%d output wakes noted against the wake rule, not compared" % (len(ins), nchk, " and ".join(CSR_IDLE), len(excl)))


def vectors(vcd, out, corrupt=None):
    cg = _load("check_cg", "check-cg.py")
    P = ports()
    ins = [(w, n) for d, w, n in P if d == "input"]
    outs = [(w, n) for d, w, n in P if d == "output"]
    # The dump's ports are the block's, but for the CSR ports (absent: tied
    # idle) and nothing else (tools/check-port-dump.py holds it to that).
    have = set()
    with open(vcd) as f:
        for line in f:
            if line.startswith("$var"):
                have.add(line.split()[4])
            elif line.startswith("$enddefinitions"):
                break
    want = [n for _, n in ins + outs if n not in ("csr_req",) + CSR_IDLE]
    missing = [n for n in want if n not in have]
    if missing:
        raise SystemExit("check-rcu-block: %s lacks %s" % (vcd, ", ".join(missing[:8])))
    snaps = cg.read_vcd(vcd, "u_rcu", want, "core_clk")
    cc = None
    if corrupt:
        c, p = corrupt.split(":", 1)
        cc = (int(c), p)
        if p not in [n for _, n in outs]:
            raise SystemExit("check-rcu-block: --corrupt: %s is not an output" % p)
    last_i, last_o = {}, {}
    with open(out, "w") as f:
        for t, s in enumerate(snaps):
            f.write("C %d 0\n" % t)
            for k, (w, n) in enumerate(ins):
                v = s.get(n, 0)
                if last_i.get(n) != v:
                    f.write("I %d %x\n" % (k, v))
                    last_i[n] = v
            for k, (w, n) in enumerate(outs):
                v = s.get(n, 0)
                if cc and cc == (t, n):
                    v ^= 1
                if last_o.get(n) != v:
                    f.write("O %d %x\n" % (k, v))
                    last_o[n] = v
            f.write("E %d 0\n" % t)
    return len(snaps)


def control_point(vcd, before):
    """A cycle and output for the corrupt-one-output control: the first
    cycle before `before` at which the model drives an output valid, else
    the cycle just before it, on the first output compared."""
    cg = _load("check_cg", "check-cg.py")
    outs = [n for d, w, n in ports() if d == "output" and not n.endswith("_wake")
            and n not in CSR_IDLE]
    snaps = cg.read_vcd(vcd, "u_rcu", outs, "core_clk")
    end = min(before, len(snaps))
    for t in range(end):
        for n in outs:
            if n.endswith("_valid") and snaps[t].get(n, 0):
                return t, n
    if end == 0:
        return None
    return end - 1, outs[0]


def run(d, stim, kernel, keep=False):
    n = sum(1 for l in open(stim) if l.startswith("C "))
    r = subprocess.run([os.path.join(d, "tb"), "+stim=" + stim, "+n=%d" % n,
                        "+keep=%d" % (1 if keep else 0),
                        "+maxp=%s" % os.environ.get("RCUBLK_MAXP", "40")],
                       capture_output=True, text=True)
    txt = r.stdout + r.stderr
    sys.stdout.write("".join(l + "\n" for l in txt.splitlines()
                             if l.startswith("RCUBLK") or "Assertion" in l or "%Error" in l))
    m = re.search(r"RCUBLK DONE cycles (\d+) outputs (\d+) wakes (\d+) mismatches (\d+) "
                  r"wake_misses (\d+)", txt)
    if m and m.group(4) == "0" and r.returncode == 0:
        print("%s: %s cycles, %s outputs checked each cycle: PASS" % (kernel, m.group(1), m.group(2)))
        return 0
    return 1


def main():
    a = sys.argv[1:]
    if a[:1] == ["build"] and len(a) == 2:
        build(a[1])
    elif a[:1] == ["vectors"] and len(a) in (3, 5):
        corrupt = a[4] if len(a) == 5 and a[3] == "--corrupt" else None
        print("%d cycles" % vectors(a[1], a[2], corrupt))
    elif a[:1] == ["control-point"] and len(a) == 3:
        cp = control_point(a[1], int(a[2]))
        print("%d:%s" % cp if cp else "none")
    elif a[:1] == ["run"] and len(a) in (4, 5):
        return run(a[1], a[2], a[3], keep=a[4:] == ["--keep"])
    else:
        sys.exit(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main())
