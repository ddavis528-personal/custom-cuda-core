//===-- gen_dec.cpp - write rtl/rcu/rcu_dec_pkg.sv from the model's decode -===//
//
// The RTL's op-class decode is the model's (sim/rcu/rcu_decode.h), written
// out as one case per opcode, so the two cannot drift (RI-21 (4); TI's
// generated package replaces it, TI rev 378). test/rcu/run-rtl.sh rebuilds
// this and fails if rtl/rcu/rcu_dec_pkg.sv differs from what it prints.
// Usage: gen_dec > rtl/rcu/rcu_dec_pkg.sv
//===----------------------------------------------------------------------===//
#include <cstdio>
#include <string>
#include <vector>
#include "rcu_decode.h"

using namespace ccv::skel;
namespace R = ccv::rcu;

namespace {

// Field layout of a class vector, LSB first: name, width.
struct Field { const char *name; unsigned w; };
const Field kFields[] = {{"UNIT", 3},  {"RK", 5},      {"MK", 3},      {"GUARDED", 1},
                         {"PDATA", 1}, {"GDST", 1},    {"ISLOT", 2},   {"IMMU", 1},
                         {"IREG", 1},  {"READS", 3},   {"BSRC", 2},    {"XSRC", 2},
                         {"DSRC", 2}};
constexpr unsigned kNone = 7;   // UNIT of an opcode with no class (or an atomic on no step)

unsigned src2(int s) { return s < 0 ? 3u : unsigned(s); }

uint64_t pack(const R::OpClass &oc) {
  const unsigned v[] = {unsigned(oc.unit), unsigned(oc.rk), unsigned(oc.mk), oc.guarded, oc.pdata,
                        oc.gdst, src2(oc.imm_slot), oc.imm_used, oc.ireg, oc.reads & 7u,
                        src2(oc.base_src), src2(oc.index_src), src2(oc.data_src)};
  uint64_t r = 0;
  unsigned at = 0, i = 0;
  for (const Field &f : kFields) {
    r |= uint64_t(v[i++] & ((1u << f.w) - 1)) << at;
    at += f.w;
  }
  return r;
}

std::string hex(uint64_t v, unsigned w) {
  char b[32];
  std::snprintf(b, sizeof b, "%u'h%0*llx", w, int((w + 3) / 4), (unsigned long long)v);
  return b;
}

}  // namespace

int main() {
  unsigned W = 0;
  for (const Field &f : kFields) W += f.w;
  const unsigned OPC_W = 9;
  static_assert(kOpCopy < (1u << 9), "the copy's opcode fits 9 bits");
  const uint64_t none = kNone;
  std::printf("// Generated by test/rcu/gen_dec.cpp from sim/rcu/rcu_decode.h (the model's\n"
              "// op-class decode, RI-21 (4)); never hand-edit. test/rcu/run-rtl.sh fails if\n"
              "// this file is stale. TI's generated package replaces it (TI rev 378).\n"
              "//\n"
              "// rcu_cls(opcode, done_row, pcopy) returns an issue's class as the model\n"
              "// decodes it: pcopy is the copy's \"writes a predicate and the zero GPR\"\n"
              "// (pwe && dst == 0), read only for the copy's opcode; done_row picks an\n"
              "// atomic's step. A continuation has no class: its caller gates it.\n"
              "// SFU ops class as lane ops, as in the model (Unit Sfu awaits RA-16 (b)).\n"
              "package rcu_dec_pkg;\n\n");
  std::printf("  localparam int unsigned OPC_W = %u;\n", OPC_W);
  std::printf("  localparam int unsigned CLS_W = %u;\n", W);
  unsigned at = 0;
  for (const Field &f : kFields) {
    std::printf("  localparam int unsigned CLS_%s = %u, CLS_%s_W = %u;\n", f.name, at, f.name, f.w);
    at += f.w;
  }
  const char *units[] = {"LANE", "SFU", "MEM", "RONLY", "COLL", "COPY", "PCOPY"};
  for (unsigned u = 0; u != 7; ++u) std::printf("  localparam logic [2:0] U_%s = 3'd%u;\n", units[u], u);
  std::printf("  localparam logic [2:0] U_NONE = 3'd%u;\n", kNone);
  const char *rks[] = {"NONE", "BRA", "CALL", "RET", "PAND", "POR", "PXOR", "PMOVI", "MOVI",
                       "SHIDXI", "SHIDXR", "SHUP", "SHDN", "SHBF", "VANY", "VALL", "BALLOT", "UNBAL"};
  for (unsigned k = 0; k != sizeof rks / sizeof *rks; ++k)
    std::printf("  localparam logic [4:0] RK_%s = 5'd%u;\n", rks[k], k);
  const char *mks[] = {"NONE", "LOAD", "STORE", "PLOAD", "PSTORE", "FENCE"};
  for (unsigned k = 0; k != sizeof mks / sizeof *mks; ++k)
    std::printf("  localparam logic [2:0] MK_%s = 3'd%u;\n", mks[k], k);

  std::printf("\n  function automatic logic [CLS_W-1:0] rcu_cls(input logic [OPC_W-1:0] opc,\n"
              "                                              input logic [1:0] drow,\n"
              "                                              input logic pcopy);\n"
              "    logic [CLS_W-1:0] c;\n"
              "    c = %s;\n"
              "    case (opc)\n", hex(none, W).c_str());
  for (unsigned code = 1; code != (1u << OPC_W); ++code) {
    const OpInfo *op = code == kOpCopy ? nullptr : opByCode(code);
    if (code != kOpCopy && !op) continue;
    R::OpClass oc;
    const OpInfo *d;
    if (code == kOpCopy) {
      R::OpClass pc;
      rcudec::decodeClass(code, 0, false, 1, oc, d);
      rcudec::decodeClass(code, 0, true, R::kZero, pc, d);
      std::printf("      %u: c = pcopy ? %s : %s;   // copy-only (A-38)\n", code,
                  hex(pack(pc), W).c_str(), hex(pack(oc), W).c_str());
      continue;
    }
    if (op->cls == kAtomic) {
      std::printf("      %u: case (drow)   // %s: its step by done_row (OI-85)\n", code, op->name);
      for (unsigned row = 0; row != 4; ++row)
        if (rcudec::decodeClass(code, row, false, 1, oc, d))
          std::printf("            2'd%u: c = %s;   // %s\n", row, hex(pack(oc), W).c_str(), d->name);
      std::printf("            default: c = %s;\n          endcase\n", hex(none, W).c_str());
      continue;
    }
    rcudec::decodeClass(code, 0, false, 1, oc, d);
    std::printf("      %u: c = %s;   // %s\n", code, hex(pack(oc), W).c_str(), op->name);
  }
  std::printf("      default: c = %s;\n    endcase\n    rcu_cls = c;\n  endfunction\n\n",
              hex(none, W).c_str());
  std::printf("endpackage\n");
  return 0;
}
