#!/usr/bin/env python3
"""The RTL's event monitor (docs/rcu-impl.md section 5, step 3): a sim-only
task, written into a testbench that holds ccv_rcu, that derives the model's
events (sim/rcu/rcu_core.h's Ev, docs/rcu-model.md's table) from the RTL's
state each cycle and writes them in the model's CCV_RCU_EVLOG form,
"<cycle> <name> <a> <b> <c> <d>". Nothing here is synthesised, and the RTL
carries nothing for it: it reads the RTL's own flops and the nets between
them, by hierarchical reference.

    sv(prefix)        the task text, for a testbench where `prefix` names ccv_rcu
    read(path)        an event log, as {cycle: sorted [(name, a, b, c, d)]}
    compare(m, r, k)  the first cycle where the model's and the RTL's events
                      differ, over the kinds in k

The events each kind is derived from, and the cycle it is logged in, are in
the comment above each section of the task."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def _param(name):
    txt = open(os.path.join(ROOT, "rtl/generated/ccv_params_pkg.sv")).read()
    return int(re.search(r"localparam int %s = (\d+);" % name, txt).group(1))


ROWS = _param("CCV_P_PHYS_REGS")
NK = _param("CCV_SECTIONS")
NJ = 32 // 4
# The model's GPR write ports (rcu_core.h, Port): LW 0, SW 1, MW 2, RW 3, RS 4.
# The slice's ports into the rows: its generic ones LW 0, SW 1, RW 2 (the
# restore's row on it under gws_cr02h), then MW 3.
SLICE_TO_MODEL = (0, 1, 3, 2)

# Kinds the monitor derives; a kind it does not is left out of the compare.
# idle and wake are not compared cycle for cycle: the RTL's clock gate may
# sleep later and wake earlier than the model's idle, never the reverse
# (idle_check: the gate closed only where the model is idle).
KINDS = ("gpr_write", "gpr_row", "pred_write", "branch", "bypass_sel", "rsrc_fwd", "kill_drain", "kill_ack")
PROWS = _param("CCV_P_PRED_REGS")


def sv(prefix):
    """The task rcu_ev(t, fd): every event of cycle t, sampled after the
    cycle's inputs settle and before its rising edge."""
    s = []
    s.append("  // Generated by test/rcu/evmon.py: the RTL's events, the model's form.")
    s.append("  logic ev_gated = 1'b0;")
    s.append("  task automatic rcu_ev(input int t, input int fd);")
    # ---- gpr_write ---------------------------------------------------------
    # The rows' write cycle (rcu_bank_slice, cr02h): a port hits a row in a
    # slice when it acts there and its row decodes to it. The event is the
    # model's: the row, the lanes the port writes (each slice J its 4), the
    # sections it writes (a narrow write's zero fill above it included, as
    # the model counts it), and the model's port (RS for the restore's row).
    s.append("    logic [31:0] gl[5];")
    s.append("    logic [3:0]  gs[5];")
    s.append("    int          gr[5];")
    s.append("    logic        gv[5];")
    s.append("    for (int p = 0; p < 5; p++) begin gl[p] = '0; gs[p] = '0; gr[p] = -1; gv[p] = 1'b0; end")
    for k in range(NK):
        for j in range(NJ):
            sl = "%s.g_k[%d].g_j[%d].u_slice" % (prefix, k, j)
            s.append("    for (int p = 0; p < 4; p++)")
            s.append("      for (int r = 0; r < %d; r++)" % ROWS)
            s.append("        if (%s.hit_cr02h[r*4 + p]) begin" % sl)
            s.append("          automatic int q = (p == 0) ? 0 : (p == 1) ? 1 : (p == 3) ? 2 : %s.gws_cr02h ? 4 : 3;" % sl)
            s.append("          if (gv[q] && gr[q] != r) $display(\"RCU-EV two rows on port %%0d at %%0d\", q, t);")
            s.append("          gv[q] = 1'b1; gr[q] = r;")
            s.append("          gl[q][%d +: 4] = gl[q][%d +: 4] | %s.plm_cr02h[p*4 +: 4];" % (4 * j, 4 * j, sl))
            s.append("          gs[q][%d] = 1'b1;" % k)
            s.append("        end")
    s.append("    for (int q = 0; q < 5; q++)")
    s.append("      if (gv[q]) $fdisplay(fd, \"%0d gpr_write %0d %0d %0d %0d\", t, gr[q], gl[q], gs[q], q);")
    # gpr_row (the log's, not a trace event): each written row as the write
    # leaves it, every lane, from the slices' row D (row_d_cr02h).
    s.append("    for (int q = 0; q < 5; q++)")
    s.append("      if (gv[q]) begin")
    s.append("        logic [31:0] v[32];")
    for k in range(NK):
        for j in range(NJ):
            sl = "%s.g_k[%d].g_j[%d].u_slice" % (prefix, k, j)
            s.append("        for (int i = 0; i < 4; i++) v[%d + i][%d +: 8] = %s.row_d_cr02h[gr[q]*32 + 8*i +: 8];"
                     % (4 * j, 8 * k, sl))
    s.append("        $fwrite(fd, \"%0d gpr_row %0d\", t, gr[q]);")
    s.append("        for (int l = 0; l < 32; l++) $fwrite(fd, \" %0h\", v[l]);")
    s.append("        $fwrite(fd, \"\\n\");")
    s.append("      end")
    # ---- pred_write --------------------------------------------------------
    # The predicate rows' write cycle (rcu_pred, cr02h): each port hitting a
    # row, the row's value after that port's write (its lanes from its data,
    # the rest as they stand), its lanes, and the model's port: PL 0 (merge
    # ports 0-3), PR 2 (4), PC 3 (5-8), PG 4 (9-12), PM 1 (MIU's, 13-16).
    pr = "%s.u_pred" % prefix
    s.append("    for (int r = 0; r < %d; r++)" % PROWS)
    s.append("      for (int q = 0; q < 17; q++)")
    s.append("        if (%s.hit_cr02h[r*17 + q]) begin" % pr)
    s.append("          automatic logic [31:0] m = %s.p_m_cr02h[q*32 +: 32];" % pr)
    s.append("          automatic logic [31:0] v = (%s.row_cr02h[r*32 +: 32] & ~m) | (%s.p_d_cr02h[q*32 +: 32] & m);"
             % (pr, pr))
    s.append("          automatic int mp = q < 4 ? 0 : q == 4 ? 2 : q < 9 ? 3 : q < 13 ? 4 : 1;")
    s.append("          $fdisplay(fd, \"%0d pred_write %0d %0d %0d %0d\", t, r, v, m, mp);")
    s.append("        end")
    # ---- branch --------------------------------------------------------------
    # R's done fields (rcu_r, cr03h, the cycle they are flopped for the done):
    # a bra, call or ret with R valid. tag, taken, mask, aux. The model logs
    # the op in A, a cycle before: t - 1.
    r = "%s.u_r" % prefix
    s.append("    if (%s.r_v_cr03h && %s.k_br_cr03h)" % (r, r))
    s.append("      $fdisplay(fd, \"%%0d branch %%0d %%0d %%0d %%0d\", t - 1, %s.tag_cr03h, %s.k_br_cr03h & |%s.act_cr03h,"
             % (r, r, r))
    s.append("                %s.k_ret_cr03h ? %s.same_cr03h : %s.act_cr03h, %s.k_ret_cr03h ? %s.aux_cr03h : 32'd0);"
             % (r, r, r, r, r))
    # ---- bypass_sel ----------------------------------------------------------
    # The bypass compare (rcu_lanes, stage I, cr02h): each slot's port with a
    # select, the select and the slot's footprint.
    ln = "%s.u_lanes" % prefix
    s.append("    for (int p = 0; p < %d * %s.NP; p++)" % (NK, ln))
    s.append("      if (%s.bsel_cr02h[p*%s.WB +: %s.WB] != 0)" % (ln, ln, ln))
    s.append("        $fdisplay(fd, \"%%0d bypass_sel %%0d %%0d %%0d %%0d\", t, p / %s.NP, p %% %s.NP,"
             % (ln, ln))
    s.append("                  %s.bsel_cr02h[p*%s.WB +: %s.WB], %s.foot_cr02h[(p / %s.NP)*%d +: %d]);"
             % (ln, ln, ln, ln, ln, NK, NK))
    # ---- rsrc_fwd ------------------------------------------------------------
    # R0 and R1 read in A (rcu_bank_slice, cr03h): a source R's class reads,
    # with an MW write landing in the same row now, in any slice, forwards.
    # R source, MIU slot, row.
    s.append("    begin")
    s.append("      logic [2:0] rf[2];")
    s.append("      int rr[2], rs[2];")
    s.append("      for (int q = 0; q < 2; q++) begin rf[q] = 0; rr[q] = 0; rs[q] = 0; end")
    for k in range(NK):
        for j in range(NJ):
            sl = "%s.g_k[%d].g_j[%d].u_slice" % (prefix, k, j)
            s.append("      for (int q = 0; q < 2; q++)")
            s.append("        if (%s.rv_cr03h && %s.u_r.cls_cr02h[rcu_dec_pkg::CLS_READS + q] && %s.mw_act_cr02h &&"
                     % (sl, prefix, sl))
            s.append("            %s.rr_row_cr03h[q*8 +: 8] == %s.mw_row_cr02h &&" % (sl, sl))
            s.append("            %s.rr_row_cr03h[q*8 +: 8] != %s.ZROW) begin" % (sl, sl))
            s.append("          rf[q] = 1; rr[q] = %s.mw_row_cr02h; rs[q] = %s.mw_slot_cr02h;" % (sl, sl))
            s.append("        end")
    s.append("      for (int q = 0; q < 2; q++)")
    s.append("        if (rf[q] != 0) $fdisplay(fd, \"%0d rsrc_fwd %0d %0d %0d 0\", t, q, rs[q], rr[q]);")
    s.append("    end")
    # ---- kill_drain, kill_ack ------------------------------------------------
    # The kill (rcu_kill): K+1, its mask and epoch from ccv_rcu's kill
    # detector and the drain as loaded at K (kd + 1, the model's count), logged
    # in kill_valid's cycle, K - 1 (the detector flops it at K), as the model
    # takes the kill in the cycle it arrives: t - 2. The ack: kill_ack rising, with its epoch.
    k = "%s.u_kill" % prefix
    s.append("    if (%s.kvd_cr02h)" % k)
    s.append("      $fdisplay(fd, \"%%0d kill_drain %%0d %%0d %%0d 0\", t - 2, %s.kill_detect_km_cr02h,"
             % prefix)
    s.append("                %s.kill_detect_ep_cr02h, %s.kd_cr02h + 1);" % (prefix, k))
    s.append("    if (%s.rdy_cr01h)" % k)
    s.append("      $fdisplay(fd, \"%%0d kill_ack %%0d 0 0 0\", t, %s.kaep_q_cr03h);" % k)
    # ---- the clock gate ------------------------------------------------------
    # Not a model event: ccv_common_clk's gated (the coming edge will not
    # reach the block), each change, for idle_check.
    s.append("    if (%s.cg_gated_cr02h !== ev_gated) begin" % prefix)
    s.append("      $fdisplay(fd, \"%%0d gated %%0d 0 0 0\", t, %s.cg_gated_cr02h);" % prefix)
    s.append("      ev_gated = %s.cg_gated_cr02h;" % prefix)
    s.append("    end")
    s.append("  endtask")
    return "\n".join(s)


def read(path, kinds=KINDS, shift=0):
    """{cycle: sorted events} from a log, cycles moved by shift."""
    ev = {}
    for line in open(path):
        p = line.split()
        if len(p) < 2 or p[1] not in kinds:
            continue
        base = 16 if p[1] == "gpr_row" else 10
        ev.setdefault(int(p[0]) + shift, []).append(tuple([p[1], int(p[2])] + [int(x, base) for x in p[3:]]))
    # A row two ports write in one cycle: the model logs it after each, the
    # RTL once, after both. The last of a cycle's row values stands.
    for t, v in ev.items():
        rows = {}
        for e in v:
            if e[0] == "gpr_row":
                rows[e[1]] = e
        ev[t] = [e for e in v if e[0] != "gpr_row"] + list(rows.values())
    return {t: sorted(v) for t, v in ev.items()}


def spans(path, on, off):
    """[(cycle, state)]: a log's changes, on/off kinds or a gated line."""
    ch = []
    for line in open(path):
        p = line.split()
        if len(p) < 2:
            continue
        if on == "gated":
            if p[1] == "gated":
                ch.append((int(p[0]), p[2] == "1"))
        elif p[1] in (on, off):
            ch.append((int(p[0]), p[1] == on))
    return sorted(ch)


def idle_check(mpath, rpath, upto):
    """The first cycle below upto where the RTL's clock gate is closed and
    the model is not idle, or None. Both start awake (reset)."""
    m, r = spans(mpath, "idle", "wake"), spans(rpath, "gated", None)
    mi = rg = False
    for t in sorted({c for c, _ in m} | {c for c, _ in r}):
        if t >= upto:
            break
        for c, v in m:
            if c == t:
                mi = v
        for c, v in r:
            if c == t:
                rg = v
        if rg and not mi:
            return t
    return None


def compare(model, rtl, upto):
    """(cycle, model's, RTL's) at the first cycle below upto where they
    differ, or None."""
    for t in sorted(set(model) | set(rtl)):
        if t >= upto:
            break
        if model.get(t, []) != rtl.get(t, []):
            return t, model.get(t, []), rtl.get(t, [])
    return None
