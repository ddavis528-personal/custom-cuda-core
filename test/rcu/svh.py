#!/usr/bin/env python3
"""RCU's RTL in the SV top (CCV_RCU_RTL; RI-42, TI rev 422): the build-time
half of test/rcu/ccv_rcu_svh.sv, written from the port list so nothing of it
is checked in.

    svh.py prep --out DIR [--shim]
        DIR/ccv_rcu_rtl.sv       rtl/rcu/ccv_rcu.sv as module ccv_rcu_rtl, so
                                 the wrapper can take the name the top
                                 instantiates (ccv_rcu)
        DIR/ccv_rcu_svh_gen.svh  the wrapper's generated body: the shadow's
                                 outputs and its instance, the per-cycle
                                 writer, the RTL's power-up and the readers
                                 of its register files
        DIR/rcu_dpi.sv       --shim only: a local stand-in for gen-top's
                                 rcu_dpi (rtl/top/dpi/ccv_rcu.sv renamed,
                                 registering as its parent), until TI's lands
      and prints the sources in compile order, one a line, rcu_dec_pkg first,
      then "-I<DIR>": in place of rtl/top/dpi/ccv_rcu.sv in the SV top's list.

    svh.py compare BASE
        The run's compare: BASE.vcd (the shadow's ports, as ccv-skel's
        --port-dump writes them) and BASE.obs (the RTL's outputs) under the
        block lock-step's care masks, BASE.rtl.ev (the RTL's events) against
        BASE.ev (the shadow model's, CCV_RCU_EVLOG), then one line,
        "rcu=rtl divergences=N". Exit 0 only for N = 0.
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import evmon      # noqa: E402
import lockstep   # noqa: E402

RTL = os.path.join(ROOT, "rtl/rcu")


def ports():
    """[(dir, type, name, guard)] in declaration order; guard is the `ifdef
    macro a port sits under, or None."""
    out, guard = [], None
    for line in open(lockstep.PORTS):
        s = line.strip()
        m = re.match(r"`ifdef\s+(\w+)", s)
        if m:
            guard = m.group(1)
            continue
        if s.startswith("`endif"):
            guard = None
            continue
        m = re.match(r",?\s*(input|output)\s+(.*?)\s*(\w+)\s*,?\s*$", s)
        if m:
            out.append((m.group(1), m.group(2), m.group(3), guard))
    return out


def gen_body():
    ps = ports()
    plain = [p for p in ps if p[3] is None]
    outs = [p for p in ps if p[0] == "output"]
    s = ["// Generated by test/rcu/svh.py from rtl/top/ports/ccv_rcu_ports.svh: the",
         "// body of test/rcu/ccv_rcu_svh.sv. Not checked in; rebuilt with the top.", ""]
    # ---- the RTL ------------------------------------------------------------
    # It drives every output but the trace ids. The RTL carries none (its
    # _tid outputs are 0: rtl/rcu/ccv_rcu.sv), and the host's checks look a
    # message's oracle record up by its id, so the top's _tid nets take the
    # shadow's: trace-only sideband, never a decision. The shadow's messages
    # are the RTL's cycle for cycle (`svh.py compare`), so each id lands on
    # its own message; where they part, the compare says so.
    tids = [p for p in outs if p[2].endswith("_tid")]
    s.append("  // The RTL drives the top; its trace ids (all 0) go nowhere.")
    for d, t, n, g in tids:
        s.append("`ifdef %s" % g if g else "")
        s.append("  %s rtl_%s;" % (t, n))
        s.append("`endif" if g else "")
    s.append("  ccv_rcu_rtl u_rtl (.*")
    for d, t, n, g in tids:
        s.append("`ifdef %s" % g if g else "")
        s.append("    , .%s(rtl_%s)" % (n, n))
        s.append("`endif" if g else "")
    s.append("  );")
    for d, t, n, g in tids:
        s.append("`ifdef %s" % g if g else "")
        s.append("  assign %s = sh_%s;" % (n, n))
        s.append("`endif" if g else "")
    s.append("")
    # ---- the shadow --------------------------------------------------------
    s.append("  // The shadow's outputs: compared, never driven onto the top's nets.")
    for d, t, n, g in outs:
        if g:
            s.append("`ifdef %s" % g)
        s.append("  %s sh_%s;" % (t, n))
        if g:
            s.append("`endif")
    s.append("  rcu_dpi u_shadow (")
    first = True
    for d, t, n, g in ps:
        conn = "%s.%s(%s)" % ("" if first else ", ", n, ("sh_" + n) if d == "output" else n)
        first = False
        if g:
            s.append("`ifdef %s" % g)
        s.append("    " + conn)
        if g:
            s.append("`endif")
    s.append("  );")
    s.append("")
    # ---- the RTL's power-up, as the model's (lockstep.build) ---------------
    s.append("  // The register file powers up as the model's does (sim/rcu/rcu_block.cpp:")
    s.append("  // physical GPR p, lane l holds 0xdead0000 | p << 5 | l), so a row read")
    s.append("  // before any write compares as in the block lock-step.")
    s.append("  initial if (!$test$plusargs(\"ccv_rcu_svh_noinit\")) begin")
    for k in range(evmon.NK):
        for j in range(evmon.NJ):
            for r in range(evmon.ROWS):
                w = 0
                for l in range(4):
                    v = 0xdead0000 | r << 5 | (4 * j + l)
                    w |= ((v >> (8 * k)) & 0xff) << (8 * l)
                s.append("    u_rtl.g_k[%d].g_j[%d].u_slice.g_row[%d].rq_cr03h = 32'h%08x;" % (k, j, r, w))
    s.append("  end")
    s.append("")
    # ---- the RTL's register files, read by the host -------------------------
    s.append("  // The RTL's register files as the host reads them (ccv_rcu_rtl_gpr,")
    s.append("  // ccv_rcu_rtl_pred): GPR row r, lane 4J+i is byte K of slice (K, J)'s")
    s.append("  // row r, bits 8i; predicate row p is rcu_pred's row p, a bit a lane.")
    s.append("  logic [31:0] rtl_gpr [%d][32];" % evmon.ROWS)
    s.append("  logic [31:0] rtl_pred [%d];" % evmon.PROWS)
    s.append("  for (genvar K = 0; K < %d; K++) begin : g_rk" % evmon.NK)
    s.append("    for (genvar J = 0; J < %d; J++) begin : g_rj" % evmon.NJ)
    s.append("      for (genvar R = 0; R < %d; R++) begin : g_rr" % evmon.ROWS)
    s.append("        for (genvar I = 0; I < 4; I++) begin : g_ri")
    s.append("          assign rtl_gpr[R][4*J+I][8*K +: 8] = u_rtl.g_k[K].g_j[J].u_slice.g_row[R].rq_cr03h[8*I +: 8];")
    s.append("        end")
    s.append("      end")
    s.append("    end")
    s.append("  end")
    s.append("  for (genvar P = 0; P < %d; P++) begin : g_rp" % evmon.PROWS)
    s.append("    assign rtl_pred[P] = 32'(u_rtl.u_pred.g_row[P].pq_cr02h);")
    s.append("  end")
    # The control's flip: lane bit 0 of a stored row, flipped at the next
    # edge (non-blocking: Verilator refuses a blocking write, outside an
    # initial block, to a register the RTL assigns non-blocking).
    s.append("  bit flip_req = 1'b0;")
    s.append("  int flip_row, flip_lane;")
    s.append("  always @(posedge core_clk) if (flip_req) begin")
    s.append("    flip_req = 1'b0;")
    s.append("    case (flip_row)")
    for r in range(evmon.ROWS):
        s.append("      %d: case (flip_lane)" % r)
        for ln in range(32):
            j, i = ln // 4, ln % 4
            s.append("        %d: u_rtl.g_k[0].g_j[%d].u_slice.g_row[%d].rq_cr03h <= "
                     "u_rtl.g_k[0].g_j[%d].u_slice.g_row[%d].rq_cr03h ^ 32'h%08x;" % (ln, j, r, j, r, 1 << (8 * i)))
        s.append("        default: ;")
        s.append("      endcase")
    s.append("      default: ;")
    s.append("    endcase")
    s.append("  end")
    s.append("")
    # ---- the per-cycle writer ----------------------------------------------
    # BASE.vcd: every port outside an `ifdef, inputs as they arrive and
    # outputs as the shadow drives them, under scope u_rcu, the form
    # ccv-skel's --port-dump writes and lockstep.read_dump reads. BASE.obs:
    # the RTL's outputs one line a cycle, packed as the lock-step's replay
    # packs them (sorted by name, the first at bit 0).
    ids = {}
    for i, (d, t, n, g) in enumerate(plain):
        ids[n] = "p%d" % i
    s.append("  int sv_fv = 0, sv_fo = 0, sv_fe = 0, sv_t = 0;")
    s.append("  string sv_base;")
    for d, t, n, g in plain:
        if n == lockstep.CLOCK:
            continue
        s.append("  %s sv_q_%s;" % (t, n))
    s.append("  initial if ($value$plusargs(\"ccv_rcu_svh=%s\", sv_base)) begin")
    s.append("    sv_fv = $fopen({sv_base, \".vcd\"}, \"w\");")
    s.append("    sv_fo = $fopen({sv_base, \".obs\"}, \"w\");")
    s.append("    sv_fe = $fopen({sv_base, \".rtl.ev\"}, \"w\");")
    s.append("    $fdisplay(sv_fv, \"$timescale 1ns $end\");")
    s.append("    $fdisplay(sv_fv, \"$scope module %s $end\");" % lockstep.SCOPE)
    for d, t, n, g in plain:
        s.append("    $fdisplay(sv_fv, \"$var wire %%0d %s %s $end\", $bits(%s));" % (ids[n], n, n))
    s.append("    $fdisplay(sv_fv, \"$upscope $end\");")
    s.append("    $fdisplay(sv_fv, \"$enddefinitions $end\");")
    s.append("  end")
    souts = sorted(n for d, t, n, g in plain if d == "output")
    s.append("  // The cycle's values, sampled at its rising edge before it updates")
    s.append("  // anything: what a register would take.")
    s.append("  always @(posedge core_clk) if (sv_fv != 0) begin")
    s.append("    $fdisplay(sv_fv, \"#%0d\", 2 * sv_t);")
    for d, t, n, g in plain:
        if n == lockstep.CLOCK:
            continue
        v = ("sh_" + n) if d == "output" else n
        s.append("    if (sv_t == 0 || %s !== sv_q_%s) begin $fdisplay(sv_fv, \"b%%b %s\", %s); sv_q_%s = %s; end"
                 % (v, n, ids[n], v, n, v))
    s.append("    $fdisplay(sv_fv, \"0%s\");" % ids[lockstep.CLOCK])
    s.append("    $fdisplay(sv_fv, \"#%0d\", 2 * sv_t + 1);")
    s.append("    $fdisplay(sv_fv, \"1%s\");" % ids[lockstep.CLOCK])
    s.append("    $fdisplay(sv_fo, \"%%h\", {%s});" % ", ".join(reversed(souts)))
    s.append("    rcu_ev(sv_t, sv_fe);")
    s.append("    sv_t = sv_t + 1;")
    s.append("  end")
    s.append("  final if (sv_fv != 0) begin")
    s.append("    $fclose(sv_fv);")
    s.append("    $fclose(sv_fo);")
    s.append("    $fclose(sv_fe);")
    s.append("  end")
    s.append("")
    s.append(evmon.sv("u_rtl"))
    return "\n".join(s) + "\n"


def prep(a):
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    src = open(os.path.join(RTL, "ccv_rcu.sv")).read()
    n = len(re.findall(r"^module ccv_rcu\b", src, re.M))
    if n != 1:
        sys.exit("svh.py: rtl/rcu/ccv_rcu.sv has %d 'module ccv_rcu' headers, not 1" % n)
    rtl = re.sub(r"^module ccv_rcu\b", "module ccv_rcu_rtl", src, flags=re.M)
    hdr = "// Generated by test/rcu/svh.py: rtl/rcu/ccv_rcu.sv as ccv_rcu_rtl.\n"

    def put(name, text):
        p = os.path.join(out, name)
        if not os.path.exists(p) or open(p).read() != text:
            open(p, "w").write(text)
        return p

    put("ccv_rcu_rtl.sv", hdr + rtl)
    put("ccv_rcu_svh_gen.svh", gen_body())
    files = [os.path.join(RTL, "rcu_dec_pkg.sv")]
    files += sorted(os.path.join(RTL, f) for f in os.listdir(RTL)
                    if f.endswith(".sv") and f not in ("rcu_dec_pkg.sv", "ccv_rcu.sv"))
    files += [os.path.join(out, "ccv_rcu_rtl.sv"), os.path.join(HERE, "ccv_rcu_svh.sv")]
    if a.shim:
        shim = open(os.path.join(ROOT, "rtl/top/dpi/ccv_rcu.sv")).read()
        shim = re.sub(r"^module ccv_rcu\b", "module rcu_dpi", shim, flags=re.M)
        # Register as the wrapper: the host binds a shim to its block by the
        # last name of its path (sim/skel/dpi_host.cpp, ccv_dpi_register).
        reg = 'ccv_dpi_register($sformatf("%m"))'
        if reg not in shim:
            sys.exit("svh.py --shim: rtl/top/dpi/ccv_rcu.sv no longer registers as %s" % reg)
        shim = shim.replace(reg, 'ccv_dpi_register(svh_parent($sformatf("%m")))')
        shim = shim.replace("  int h;\n", "  int h;\n  function automatic string svh_parent(input string p);\n"
                            "    for (int i = p.len() - 1; i >= 0; i--) if (p[i] == \".\") return p.substr(0, i - 1);\n"
                            "    return p;\n  endfunction\n", 1)
        files.append(put("rcu_dpi.sv", "// Generated by test/rcu/svh.py --shim: a local stand-in for "
                         "gen-top's rcu_dpi.\n" + shim))
    for f in files:
        print(f)
    print("-I" + out)


def compare(a):
    base = a.base[:-4] if a.base.endswith(".vcd") else a.base
    r = subprocess.run([sys.executable, os.path.join(HERE, "lockstep.py"), "--replayed", base + ".vcd"]
                       + (["--control", a.control] if a.control else []),
                       capture_output=True, text=True)
    sys.stdout.write(r.stdout)
    sys.stderr.write(r.stderr)
    n = sum(1 for l in r.stdout.splitlines() if " DIVERGE" in l)
    if r.returncode and not n:
        n = 1
    print("rcu=rtl divergences=%d" % n)
    return 0 if n == 0 else 1


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("prep")
    p.add_argument("--out", required=True)
    p.add_argument("--shim", action="store_true")
    c = sub.add_parser("compare")
    c.add_argument("base")
    c.add_argument("--control", choices=("ev", "gate", "row"))
    a = ap.parse_args()
    return prep(a) if a.cmd == "prep" else compare(a)


if __name__ == "__main__":
    sys.exit(main())
