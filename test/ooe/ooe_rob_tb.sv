//===-- ooe_rob_tb.sv - the four per-warp ROBs as the stage holds them -----===//
//
// Bench harness only, never RTL (OA-24, DA rev 104): S instances of
// ooe_rob_w, one a tier-1 slot, behind the ports the single ooe_rob had, so
// test/ooe/rob_tb.cpp drives and compares them unchanged. Each instance
// takes its slot's slice of the per-slot ports and every lane of the
// shared ones (Rename 2's fills, RCU's dones, MIU's completions), keyed on
// its own WID inside. The frees and their leads are ORed here as
// ooe_freelist ORs them at its input in the stage (OA grants that input 2.0
// NGD, an OR4 behind the flop): there is no logic between the instances in
// the RTL.
//===----------------------------------------------------------------------===//
module ooe_rob_tb #(
  parameter int S = 4,
  parameter int D = 32,
  parameter int RP = 2,
  parameter int A = 4,
  parameter int ND = 7,
  parameter int NM = 4,
  parameter int GW = 10,
  parameter int GR = 8,
  parameter int NG = 192,
  parameter int NS = 4,
  parameter int PW = 6,
  parameter int NP = 48,
  parameter int LB = 6,
  parameter int LT = 3,
  parameter int NK = 4,
  parameter int PCW = 48,
  parameter int CW = 4,
  parameter int VA = 64,
  parameter int BS = ND - 2,
  localparam int NSB = (NS > 0) ? NS : 1,
  localparam int LS = (S > 1) ? $clog2(S) : 1,
  localparam int LD = $clog2(D),
  localparam int TW = LS + LD,
  localparam int LA = $clog2(A + 1),
  localparam int LK = (NK > 1) ? $clog2(NK) : 1,
  localparam int NR = 4
) (
  input  logic                    ooe_core_clk,
  input  logic                    ooe_rst_r00h,
  input  logic [S-1:0]            al_l_cq01h,
  input  logic [S*LA-1:0]         al_n_cq02h,
  input  logic [S*A-1:0]          al_nop_cq02h,
  input  logic [S*A-1:0]          al_flt_cq02h,
  input  logic [S*A*CW-1:0]       al_cause_cq02h,
  input  logic [S*A*31-1:0]       al_pc_cq02h,
  input  logic [S*A*16-1:0]       al_pchi_cq02h,
  input  logic [S*A*32-1:0]       al_gm_cq02h,
  input  logic                    fl_l_cq01h,
  input  logic                    fl_brl_cq01h,
  input  logic [A-1:0]            fl_v_cq02h,
  input  logic [A*LS-1:0]         fl_slot_cq02h,
  input  logic [A-1:0]            fl_nop_cq02h,
  input  logic [A-1:0]            fl_mem_cq02h,
  input  logic [A*2-1:0]          fl_rs_cq02h,
  input  logic [A-1:0]            fl_gwe_cq02h,
  input  logic [A*4-1:0]          fl_dst_cq02h,
  input  logic [A*GW-1:0]         fl_gname_cq02h,
  input  logic [A*GW-1:0]         fl_gold_cq02h,
  input  logic [A*NSB-1:0]        fl_gsec_cq02h,
  input  logic [A-1:0]            fl_pwe_cq02h,
  input  logic [A*2-1:0]          fl_pdst_cq02h,
  input  logic [A*PW-1:0]         fl_pname_cq02h,
  input  logic [A*PW-1:0]         fl_pold_cq02h,
  input  logic [A-1:0]            fl_pfree_cq02h,
  input  logic [A-1:0]            fl_br_cq02h,
  input  logic [A*LK-1:0]         fl_ckpt_cq02h,
  input  logic [A-1:0]            fl_ptaken_cq02h,
  input  logic [A-1:0]            fl_ret_cq02h,
  input  logic [A*32-1:0]         fl_gmask_cq02h,
  input  logic [A*PCW-1:0]        fl_pcn_cq02h,
  input  logic [A*PCW-1:0]        fl_tgt_cq02h,
  input  logic [A*16-1:0]         fl_pchi_cq02h,
  input  logic [A*NSB-1:0]        fl_gnsec_cq02h,
  input  logic [A-1:0]            fl_palloc_cq02h,
  input  logic [A-1:0]            fl_store_cq02h,
  input  logic [S-1:0]            ev_l_cq01h,
  input  logic [S*D*NR-1:0]       ev_owe_cq02h,
  input  logic [S*D-1:0]          ev_cpi_cq02h,
  input  logic [S*D-1:0]          ev_cpl_cq02h,
  input  logic [S*D*2-1:0]        ev_rsf_cq02h,
  input  logic [S*D-1:0]          ev_miu_cq02h,
  input  logic [ND-1:0]           dn_l_cq01h,
  input  logic [ND*TW-1:0]        dn_tag_cq02h,
  input  logic [ND*2-1:0]         dn_row_cq02h,
  input  logic                    dn_taken_cq02h,
  input  logic [31:0]             dn_mask_cq02h,
  input  logic [31:0]             dn_aux_cq02h,
  input  logic [NM-1:0]           cm_l_cq01h,
  input  logic [NM*TW-1:0]        cm_tag_cq02h,
  input  logic [NM-1:0]           cf_l_cq01h,
  input  logic [NM*CW-1:0]        cf_cause_cq02h,
  input  logic [NM*32-1:0]        cf_lanes_cq02h,
  input  logic [NM*VA-1:0]        cf_addr_cq02h,
  input  logic [S-1:0]            rel_l_cq01h,
  output logic [S*RP-1:0]         rgl_cq02h,
  output logic [S*RP-1:0]         rpl_cq02h,
  output logic                    gfree_l_cq02h,
  output logic                    pfree_l_cq02h,
  output logic [S*RP-1:0]         ret_gwe_cq03h,
  output logic [S*RP*4-1:0]       ret_dst_cq03h,
  output logic [S*RP*GW-1:0]      ret_gname_cq03h,
  output logic [S*RP-1:0]         ret_pwe_cq03h,
  output logic [S*RP*2-1:0]       ret_pdst_cq03h,
  output logic [S*RP*PW-1:0]      ret_pname_cq03h,
  output logic [NG*NSB-1:0]       gfree_cq03h,
  output logic [NP-1:0]           pfree_cq03h,
  output logic [S*LB-1:0]         run_cq02h,
  output logic [S-1:0]            reach_cq02h,
  output logic [S*LT-1:0]         ret_cq02h,
  output logic [S-1:0]            rd_l_cq03h,
  output logic [S*NK-1:0]         ckf_cq03h,
  output logic [S*LK-1:0]         rd_ckpt_cq04h,
  output logic [S*32-1:0]         rd_tmask_cq04h,
  output logic [S*PCW-1:0]        rd_tgt_cq04h,
  output logic [S-1:0]            rd_stay_cq04h,
  output logic [S-1:0]            dc_v_cq03h,
  output logic [S*LD-1:0]         dc_br_cq03h,
  output logic [S*LD-1:0]         dc_disp_cq03h,
  output logic [S-1:0]            cmt_v_cq03h,
  output logic [S*TW-1:0]         cmt_tag_cq03h,
  output logic [S-1:0]            ft_v_cq03h,
  output logic [S*CW-1:0]         ft_cause_cq03h,
  output logic [S*PCW-1:0]        ft_pc_cq03h,
  output logic [S*32-1:0]         ft_lanes_cq03h,
  output logic [S*VA-1:0]         ft_addr_cq03h
);
  // Per instance, its frees and their leads, ORed below.
  logic [S-1:0]        gfl_w, pfl_w;
  logic [S*NG*NSB-1:0] gf_w;
  logic [S*NP-1:0]     pf_w;
  for (genvar w = 0; w < S; w++) begin : g_w
    ooe_rob_w #(.SA(S), .WID(w), .D(D), .RP(RP), .A(A), .ND(ND), .NM(NM), .GW(GW), .GR(GR), .NG(NG), .NS(NS), .PW(PW), .NP(NP), .LB(LB), .LT(LT), .NK(NK), .PCW(PCW), .CW(CW), .VA(VA), .BS(BS)) u_w (
      .ooe_core_clk, .ooe_rst_r00h,
      .al_l_cq01h(al_l_cq01h[w * ($bits(al_l_cq01h) / S) +: $bits(al_l_cq01h) / S]),
      .al_n_cq02h(al_n_cq02h[w * ($bits(al_n_cq02h) / S) +: $bits(al_n_cq02h) / S]),
      .al_nop_cq02h(al_nop_cq02h[w * ($bits(al_nop_cq02h) / S) +: $bits(al_nop_cq02h) / S]),
      .al_flt_cq02h(al_flt_cq02h[w * ($bits(al_flt_cq02h) / S) +: $bits(al_flt_cq02h) / S]),
      .al_cause_cq02h(al_cause_cq02h[w * ($bits(al_cause_cq02h) / S) +: $bits(al_cause_cq02h) / S]),
      .al_pc_cq02h(al_pc_cq02h[w * ($bits(al_pc_cq02h) / S) +: $bits(al_pc_cq02h) / S]),
      .al_pchi_cq02h(al_pchi_cq02h[w * ($bits(al_pchi_cq02h) / S) +: $bits(al_pchi_cq02h) / S]),
      .al_gm_cq02h(al_gm_cq02h[w * ($bits(al_gm_cq02h) / S) +: $bits(al_gm_cq02h) / S]),
      .fl_l_cq01h,
      .fl_brl_cq01h,
      .fl_v_cq02h,
      .fl_slot_cq02h,
      .fl_nop_cq02h,
      .fl_mem_cq02h,
      .fl_rs_cq02h,
      .fl_gwe_cq02h,
      .fl_dst_cq02h,
      .fl_gname_cq02h,
      .fl_gold_cq02h,
      .fl_gsec_cq02h,
      .fl_pwe_cq02h,
      .fl_pdst_cq02h,
      .fl_pname_cq02h,
      .fl_pold_cq02h,
      .fl_pfree_cq02h,
      .fl_br_cq02h,
      .fl_ckpt_cq02h,
      .fl_ptaken_cq02h,
      .fl_ret_cq02h,
      .fl_gmask_cq02h,
      .fl_pcn_cq02h,
      .fl_tgt_cq02h,
      .fl_pchi_cq02h,
      .fl_gnsec_cq02h,
      .fl_palloc_cq02h,
      .fl_store_cq02h,
      .ev_l_cq01h(ev_l_cq01h[w * ($bits(ev_l_cq01h) / S) +: $bits(ev_l_cq01h) / S]),
      .ev_owe_cq02h(ev_owe_cq02h[w * ($bits(ev_owe_cq02h) / S) +: $bits(ev_owe_cq02h) / S]),
      .ev_cpi_cq02h(ev_cpi_cq02h[w * ($bits(ev_cpi_cq02h) / S) +: $bits(ev_cpi_cq02h) / S]),
      .ev_cpl_cq02h(ev_cpl_cq02h[w * ($bits(ev_cpl_cq02h) / S) +: $bits(ev_cpl_cq02h) / S]),
      .ev_rsf_cq02h(ev_rsf_cq02h[w * ($bits(ev_rsf_cq02h) / S) +: $bits(ev_rsf_cq02h) / S]),
      .ev_miu_cq02h(ev_miu_cq02h[w * ($bits(ev_miu_cq02h) / S) +: $bits(ev_miu_cq02h) / S]),
      .dn_l_cq01h,
      .dn_tag_cq02h,
      .dn_row_cq02h,
      .dn_taken_cq02h,
      .dn_mask_cq02h,
      .dn_aux_cq02h,
      .cm_l_cq01h,
      .cm_tag_cq02h,
      .cf_l_cq01h,
      .cf_cause_cq02h,
      .cf_lanes_cq02h,
      .cf_addr_cq02h,
      .rel_l_cq01h(rel_l_cq01h[w * ($bits(rel_l_cq01h) / S) +: $bits(rel_l_cq01h) / S]),
      .rgl_cq02h(rgl_cq02h[w * ($bits(rgl_cq02h) / S) +: $bits(rgl_cq02h) / S]),
      .rpl_cq02h(rpl_cq02h[w * ($bits(rpl_cq02h) / S) +: $bits(rpl_cq02h) / S]),
      .gfree_l_cq02h(gfl_w[w]),
      .pfree_l_cq02h(pfl_w[w]),
      .ret_gwe_cq03h(ret_gwe_cq03h[w * ($bits(ret_gwe_cq03h) / S) +: $bits(ret_gwe_cq03h) / S]),
      .ret_dst_cq03h(ret_dst_cq03h[w * ($bits(ret_dst_cq03h) / S) +: $bits(ret_dst_cq03h) / S]),
      .ret_gname_cq03h(ret_gname_cq03h[w * ($bits(ret_gname_cq03h) / S) +: $bits(ret_gname_cq03h) / S]),
      .ret_pwe_cq03h(ret_pwe_cq03h[w * ($bits(ret_pwe_cq03h) / S) +: $bits(ret_pwe_cq03h) / S]),
      .ret_pdst_cq03h(ret_pdst_cq03h[w * ($bits(ret_pdst_cq03h) / S) +: $bits(ret_pdst_cq03h) / S]),
      .ret_pname_cq03h(ret_pname_cq03h[w * ($bits(ret_pname_cq03h) / S) +: $bits(ret_pname_cq03h) / S]),
      .gfree_cq03h(gf_w[w * NG * NSB +: NG * NSB]),
      .pfree_cq03h(pf_w[w * NP +: NP]),
      .run_cq02h(run_cq02h[w * ($bits(run_cq02h) / S) +: $bits(run_cq02h) / S]),
      .reach_cq02h(reach_cq02h[w * ($bits(reach_cq02h) / S) +: $bits(reach_cq02h) / S]),
      .ret_cq02h(ret_cq02h[w * ($bits(ret_cq02h) / S) +: $bits(ret_cq02h) / S]),
      .rd_l_cq03h(rd_l_cq03h[w * ($bits(rd_l_cq03h) / S) +: $bits(rd_l_cq03h) / S]),
      .ckf_cq03h(ckf_cq03h[w * ($bits(ckf_cq03h) / S) +: $bits(ckf_cq03h) / S]),
      .rd_ckpt_cq04h(rd_ckpt_cq04h[w * ($bits(rd_ckpt_cq04h) / S) +: $bits(rd_ckpt_cq04h) / S]),
      .rd_tmask_cq04h(rd_tmask_cq04h[w * ($bits(rd_tmask_cq04h) / S) +: $bits(rd_tmask_cq04h) / S]),
      .rd_tgt_cq04h(rd_tgt_cq04h[w * ($bits(rd_tgt_cq04h) / S) +: $bits(rd_tgt_cq04h) / S]),
      .rd_stay_cq04h(rd_stay_cq04h[w * ($bits(rd_stay_cq04h) / S) +: $bits(rd_stay_cq04h) / S]),
      .dc_v_cq03h(dc_v_cq03h[w * ($bits(dc_v_cq03h) / S) +: $bits(dc_v_cq03h) / S]),
      .dc_br_cq03h(dc_br_cq03h[w * ($bits(dc_br_cq03h) / S) +: $bits(dc_br_cq03h) / S]),
      .dc_disp_cq03h(dc_disp_cq03h[w * ($bits(dc_disp_cq03h) / S) +: $bits(dc_disp_cq03h) / S]),
      .cmt_v_cq03h(cmt_v_cq03h[w * ($bits(cmt_v_cq03h) / S) +: $bits(cmt_v_cq03h) / S]),
      .cmt_tag_cq03h(cmt_tag_cq03h[w * ($bits(cmt_tag_cq03h) / S) +: $bits(cmt_tag_cq03h) / S]),
      .ft_v_cq03h(ft_v_cq03h[w * ($bits(ft_v_cq03h) / S) +: $bits(ft_v_cq03h) / S]),
      .ft_cause_cq03h(ft_cause_cq03h[w * ($bits(ft_cause_cq03h) / S) +: $bits(ft_cause_cq03h) / S]),
      .ft_pc_cq03h(ft_pc_cq03h[w * ($bits(ft_pc_cq03h) / S) +: $bits(ft_pc_cq03h) / S]),
      .ft_lanes_cq03h(ft_lanes_cq03h[w * ($bits(ft_lanes_cq03h) / S) +: $bits(ft_lanes_cq03h) / S]),
      .ft_addr_cq03h(ft_addr_cq03h[w * ($bits(ft_addr_cq03h) / S) +: $bits(ft_addr_cq03h) / S])
    );
  end
  always_comb begin
    gfree_l_cq02h = |gfl_w;
    pfree_l_cq02h = |pfl_w;
    gfree_cq03h   = '0;
    pfree_cq03h   = '0;
    for (int w = 0; w < S; w++) begin
      gfree_cq03h = gfree_cq03h | gf_w[w * NG * NSB +: NG * NSB];
      pfree_cq03h = pfree_cq03h | pf_w[w * NP +: NP];
    end
  end
endmodule
